# src/models.py

"""
Pydantic models used throughout TaskPilot AI.

These models define the exact structure that the LLM must return.
"""

from typing import Literal

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Type definitions
# ---------------------------------------------------------------------------

TaskPriority = Literal["Low", "Medium", "High"]

TaskStatus = Literal["To Do", "In Progress", "Done"]


# ---------------------------------------------------------------------------
# Team member
# ---------------------------------------------------------------------------

class TeamMember(BaseModel):
    """Represents a member of the project team."""

    name: str = Field(
        description="Name of the team member."
    )

    role: str = Field(
        description="Primary role of the team member."
    )

    skills: list[str] = Field(
        default_factory=list,
        description="Technical or professional skills of the team member."
    )


# ---------------------------------------------------------------------------
# Task
# ---------------------------------------------------------------------------

class Task(BaseModel):
    """Represents an actionable project task."""

    id: str = Field(
        description="Unique identifier for the task, such as TASK-001."
    )

    title: str = Field(
        description="Short, clear title describing the task."
    )

    description: str = Field(
        description="Detailed description of what needs to be completed."
    )

    assignee: str = Field(
        description="Name of the team member assigned to this task."
    )

    role: str = Field(
        description="Role of the assigned team member."
    )

    priority: TaskPriority = Field(
        description="Priority of the task."
    )

    estimated_hours: float = Field(
        ge=0.25,
        description="Estimated effort required to complete the task in hours."
    )

    status: TaskStatus = Field(
        default="To Do",
        description="Current status of the task."
    )


# ---------------------------------------------------------------------------
# Task plan
# ---------------------------------------------------------------------------

class TaskPlan(BaseModel):
    """Complete task plan generated by the AI."""

    project_summary: str = Field(
        description="Short summary of the project or user request."
    )

    tasks: list[Task] = Field(
        description="List of actionable tasks required to complete the project."
    )